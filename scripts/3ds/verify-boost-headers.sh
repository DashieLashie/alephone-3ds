#!/usr/bin/env bash
# Verify the Boost headers installed by install-boost-headers.sh with the 3DS
# cross compiler:
#   1. compile one TU that includes every <boost/...> header the Aleph One 3DS
#      source set includes (list generated from Source_Files at run time);
#   2. compile + link a small .3dsx that exercises the Boost facilities the
#      engine uses at runtime, and report any compiled-library, libatomic or
#      OS-entropy symbols it pulls in.
# The probe writes sdmc:/3ds/boost-probe.log when run on a 3DS / emulator.
#
# Usage:  scripts/3ds/verify-boost-headers.sh
# Output: <WORK_DIR>/boost-verify/{all_headers.cpp,boost_probe.cpp,*.o,
#         boost-probe.elf,boost-probe.3dsx,boost-probe.map}
#         and <WORK_DIR>/logs/boost-verify-build.log
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
WORK_DIR="${WORK_DIR:-$REPO_ROOT/build/3ds-deps}"
OUT="$WORK_DIR/boost-verify"
LOG="$WORK_DIR/logs/boost-verify-build.log"

fail() { echo "ERROR: $*" >&2; exit 1; }

[[ -n "${DEVKITPRO:-}" ]] || fail "DEVKITPRO is not set"
[[ -n "${DEVKITARM:-}" ]] || fail "DEVKITARM is not set"
PREFIX="$DEVKITPRO/portlibs/3ds"
[[ -f "$PREFIX/include/boost/version.hpp" ]] || fail "Boost headers not installed (run install-boost-headers.sh)"

CXX="$DEVKITARM/bin/arm-none-eabi-g++"
NM="$DEVKITARM/bin/arm-none-eabi-nm"
TDSX="$DEVKITPRO/tools/bin/3dsxtool"
[[ -x "$CXX" ]] || fail "$CXX not found"

CXXFLAGS=(-march=armv6k -mtune=mpcore -mfloat-abi=hard -mtp=soft -D__3DS__
          -std=gnu++17 -fexceptions -frtti -O2 -Wall
          -isystem "$PREFIX/include" -isystem "$DEVKITPRO/libctru/include")
LDFLAGS=(-march=armv6k -mtune=mpcore -mfloat-abi=hard -mtp=soft
         -specs=3dsx.specs -L"$DEVKITPRO/libctru/lib")

mkdir -p "$OUT" "$(dirname "$LOG")"
: >"$LOG"
run() { echo "+ $*" >>"$LOG"; "$@" >>"$LOG" 2>&1 || { tail -n 40 "$LOG" >&2; fail "command failed: $1 (see $LOG)"; }; }

# ---- 1. every boost header used by the 3DS source set -----------------------
# Excluded (not in the 3DS build): Network/** except network.h,
# network_games.*, network_dummy.cpp; Network/Metaserver, StandaloneHub,
# TCPMess, Steam; OpenGL shader renderers.
cd "$REPO_ROOT"
FILES="$(grep -rlE '#[[:space:]]*include[[:space:]]*[<"]boost/' Source_Files \
  | grep -vE '^Source_Files/(TCPMess|Steam)/' \
  | grep -vE '/(Rasterizer_Shader|RenderRasterize_Shader)\.cpp$' \
  | grep -vE '^Source_Files/Network/' || true)
$(ls Source_Files/Network/network.h Source_Files/Network/network_games.* Source_Files/Network/network_dummy.cpp 2>/dev/null \
  | xargs grep -lE '#[[:space:]]*include[[:space:]]*[<"]boost/' 2>/dev/null || true)"
HEADERS="$(echo "$FILES" | grep -v '^$' | xargs grep -hoE '#[[:space:]]*include[[:space:]]*[<"]boost/[^>"]+[>"]' \
  | sed -E 's/.*[<"](boost\/[^>"]+)[>"]/\1/' | sort -u)"
echo "==> Source files with boost includes:" | tee -a "$LOG"
echo "$FILES" | grep -v '^$' | sed 's/^/    /' | tee -a "$LOG"
{
  echo "// generated by scripts/3ds/verify-boost-headers.sh"
  for h in $HEADERS; do
    if [[ "$h" == boost/filesystem.hpp ]]; then
      echo "#ifndef A1_FS_STD  // a1_filesystem.h only includes this without A1_FS_STD"
      echo "#include <$h>"
      echo "#endif"
    else
      echo "#include <$h>"
    fi
  done
  echo 'static_assert(BOOST_VERSION >= 106900, "configure.ac requires Boost >= 1.69");'
  echo 'int boost_all_headers_marker = BOOST_VERSION;'
} >"$OUT/all_headers.cpp"
echo "==> $(echo "$HEADERS" | wc -l | tr -d ' ') distinct boost headers" | tee -a "$LOG"
run "$CXX" "${CXXFLAGS[@]}" -DA1_FS_STD -c "$OUT/all_headers.cpp" -o "$OUT/all_headers.o"
echo "    PASS compile with -DA1_FS_STD" | tee -a "$LOG"
run "$CXX" "${CXXFLAGS[@]}" -c "$OUT/all_headers.cpp" -o "$OUT/all_headers_boostfs.o"
echo "    PASS compile without A1_FS_STD (boost/filesystem.hpp header only; not linked)" | tee -a "$LOG"

# ---- 2. runtime probe -------------------------------------------------------
cat >"$OUT/boost_probe.cpp" <<'EOF'
// Exercises the Boost facilities Aleph One uses at runtime on the 3DS.
#include <3ds.h>
#include <atomic>
#include <cstdio>
#include <cstdarg>
#include <sstream>
#include <string>
#include <vector>
#include <boost/version.hpp>
#include <boost/algorithm/hex.hpp>
#include <boost/algorithm/string/predicate.hpp>
#include <boost/algorithm/string/replace.hpp>
#include <boost/container/small_vector.hpp>
#include <boost/iostreams/categories.hpp>
#include <boost/iostreams/device/array.hpp>
#include <boost/iostreams/positioning.hpp>
#include <boost/iostreams/stream.hpp>
#include <boost/iostreams/stream_buffer.hpp>
#include <boost/lockfree/spsc_queue.hpp>
#include <boost/property_tree/ini_parser.hpp>
#include <boost/property_tree/ptree.hpp>
#include <boost/property_tree/xml_parser.hpp>
#include <boost/range/adaptor/map.hpp>
#include <boost/range/any_range.hpp>
#include <boost/system/error_code.hpp>
#include <boost/tokenizer.hpp>
#include <boost/unordered/unordered_map.hpp>
#include <boost/unordered_map.hpp>
#include <boost/uuid/uuid.hpp>
#include <boost/uuid/uuid_generators.hpp>
#include <boost/uuid/uuid_io.hpp>

namespace io = boost::iostreams;
namespace pt = boost::property_tree;

static FILE* g_log;
static int g_fail;
static void say(const char* fmt, ...) {
  char buf[512]; va_list ap; va_start(ap, fmt); vsnprintf(buf, sizeof buf, fmt, ap); va_end(ap);
  std::printf("%s\n", buf);
  if (g_log) { std::fprintf(g_log, "%s\n", buf); std::fflush(g_log); }
}
#define CHECK(name, cond, ...) do { bool ok_ = (cond); if (!ok_) ++g_fail; \
  char d_[256]; std::snprintf(d_, sizeof d_, __VA_ARGS__); \
  say("%s %s: %s", ok_ ? "PASS" : "FAIL", name, d_); } while (0)

// Same shape as opened_file_device (Files/FileHandler.h): a seekable device.
class mem_device {
public:
  typedef char char_type;
  typedef io::seekable_device_tag category;
  explicit mem_device(std::string& s) : s_(s) {}
  std::streamsize read(char* p, std::streamsize n) {
    std::streamsize k = std::min<std::streamsize>(n, (std::streamsize)s_.size() - pos_);
    if (k <= 0) return -1;
    s_.copy(p, k, pos_); pos_ += k; return k;
  }
  std::streamsize write(const char* p, std::streamsize n) {
    if (pos_ + n > (std::streamsize)s_.size()) s_.resize(pos_ + n);
    s_.replace(pos_, n, p, n); pos_ += n; return n;
  }
  std::streampos seek(io::stream_offset off, std::ios_base::seekdir way) {
    io::stream_offset b = way == std::ios_base::beg ? 0 : way == std::ios_base::cur ? pos_ : (io::stream_offset)s_.size();
    pos_ = b + off; return pos_;
  }
private:
  std::string& s_; std::streamsize pos_ = 0;
};

struct Params { int a; float b; };

// libctru's default main stack is 32 KiB; the property_tree parsers overflow
// it (seen in Azahar: SP below 0x08000000, then PC 0). The game uses 1 MiB
// (ports/3ds/source/a1_3ds_platform.cpp); do the same here.
extern "C" { u32 __stacksize__ = 1024 * 1024; }

int main() {
  gfxInitDefault();
  consoleInit(GFX_TOP, nullptr);
  g_log = std::fopen("sdmc:/3ds/boost-probe.log", "w");
  say("Boost %s probe", BOOST_LIB_VERSION);

  try {
    // lockfree::spsc_queue with compile-time capacity (Sound/AudioPlayer.h)
    boost::lockfree::spsc_queue<Params, boost::lockfree::capacity<5>> q;
    std::atomic_int idx{0};
    int pushed = 0; for (int i = 0; i < 7; ++i) pushed += q.push(Params{i, i * 0.5f});
    Params p{}; int popped = 0, last = -1; while (q.pop(p)) { ++popped; last = p.a; }
    idx.store(1);
    CHECK("lockfree::spsc_queue", pushed == 5 && popped == 5 && last == 4,
          "pushed %d popped %d last %d lock_free=%d", pushed, popped, last, (int)q.is_lock_free());

    // property_tree XML + INI round trip with iptree (XML/InfoTree.cpp)
    std::istringstream xin("<marathon><opengl><texture coll=\"3\" bitmap=\"7\"/></opengl></marathon>");
    pt::iptree t; pt::read_xml(xin, t);
    int coll = t.get<int>("MARATHON.OpenGL.Texture.<xmlattr>.Coll");
    std::ostringstream xout;
    pt::write_xml(xout, t, pt::xml_writer_settings<std::string>(' ', 2));
    pt::iptree t2; std::istringstream xin2(xout.str()); pt::read_xml(xin2, t2);
    std::ostringstream iout; pt::iptree ini; ini.put("Section.Key", 42); pt::write_ini(iout, ini);
    pt::iptree ini2; std::istringstream iin(iout.str()); pt::read_ini(iin, ini2);
    CHECK("property_tree xml/ini", coll == 3 && t2.get<int>("marathon.opengl.texture.<xmlattr>.bitmap") == 7
          && ini2.get<int>("section.key") == 42, "coll=%d xml %u bytes ini=%d", coll,
          (unsigned)xout.str().size(), ini2.get<int>("section.key"));

    // boost::any_range + adaptors::values (InfoTree.h / InfoTree.cpp)
    typedef boost::any_range<const pt::iptree, boost::forward_traversal_tag, const pt::iptree, std::ptrdiff_t> range_t;
    auto eq = t.get_child("marathon.opengl").equal_range("texture");
    range_t r = boost::adaptors::values(boost::make_iterator_range(eq.first, eq.second));
    int n = 0; for (const auto& c : r) { n += c.get<int>("<xmlattr>.coll"); }
    CHECK("any_range/adaptors::values", n == 3, "sum=%d", n);

    // iostreams stream_buffer over array_source / array_sink (SoundFile.cpp, lua_script.cpp)
    char buf[16] = {0};
    { io::stream_buffer<io::array_sink> sb(buf, sizeof buf); std::ostream os(&sb); os << "hello" << 123; }
    std::string got; { io::stream_buffer<io::array_source> sb(buf, std::strlen(buf)); std::istream is(&sb); is >> got; }
    // io::stream over a seekable device (InfoTreeFileStream)
    std::string backing; { io::stream<mem_device> s(backing); s << "abcdef"; s.seekg(2); }
    io::stream<mem_device> s2(backing); s2.seekg(3); char c3 = (char)s2.get();
    CHECK("iostreams", got == "hello123" && backing == "abcdef" && c3 == 'd', "'%s' '%s' '%c'", got.c_str(), backing.c_str(), c3);

    // string algorithms, hex, tokenizer
    std::string s = "Scripts/Foo.LUA";
    boost::algorithm::replace_all(s, "/", "\\");
    std::string hx = boost::algorithm::hex(std::string("\x01\xab"));
    boost::char_separator<char> sep("|");
    boost::tokenizer<boost::char_separator<char>> tok(std::string("a|b|c"), sep);
    int ntok = 0; for (auto it = tok.begin(); it != tok.end(); ++it) ++ntok;
    CHECK("algorithm/tokenizer", boost::algorithm::iends_with(s, ".lua") && boost::algorithm::starts_with(s, "Scripts\\")
          && hx == "01AB" && ntok == 3, "s=%s hex=%s tokens=%d", s.c_str(), hx.c_str(), ntok);

    // unordered_map, small_vector, error_code
    boost::unordered_map<std::string, int> um; um["x"] = 1; um["y"] = 2;
    boost::container::small_vector<int, 6> sv; for (int i = 0; i < 8; ++i) sv.push_back(i);
    boost::system::error_code ec = boost::system::errc::make_error_code(boost::system::errc::no_such_file_or_directory);
    CHECK("unordered_map/small_vector/error_code", um.size() == 2 && sv.size() == 8 && ec,
          "um=%u sv=%u ec='%s'", (unsigned)um.size(), (unsigned)sv.size(), ec.message().c_str());

    // uuids::random_generator, constructed fresh per call like
    // WadImageCache::image_to_new_name. Seeded from std::random_device.
    std::string u1, u2;
    { boost::uuids::random_generator g; u1 = boost::uuids::to_string(g()); }
    { boost::uuids::random_generator g; u2 = boost::uuids::to_string(g()); }
    CHECK("uuid random_generator (fresh generators differ)", u1 != u2, "%s vs %s", u1.c_str(), u2.c_str());
  } catch (const std::exception& e) {
    ++g_fail; say("FAIL exception: %s", e.what());
  }

  say("RESULT: %s (%d failures). START to exit.", g_fail ? "FAILED" : "all passed", g_fail);
  if (g_log) std::fclose(g_log);
  while (aptMainLoop()) { hidScanInput(); if (hidKeysDown() & KEY_START) break; gfxFlushBuffers(); gfxSwapBuffers(); gspWaitForVBlank(); }
  gfxExit();
  return g_fail ? 1 : 0;
}
EOF
echo "==> Building runtime probe" | tee -a "$LOG"
run "$CXX" "${CXXFLAGS[@]}" -c "$OUT/boost_probe.cpp" -o "$OUT/boost_probe.o"
run "$CXX" "${LDFLAGS[@]}" "$OUT/boost_probe.o" -o "$OUT/boost-probe.elf" \
    -Wl,-Map,"$OUT/boost-probe.map" -Wl,--trace-symbol=getentropy -Wl,--trace-symbol=arc4random \
    -lctru -lm
echo "    PASS link (no Boost libraries, no -latomic)" | tee -a "$LOG"
if [[ -x "$TDSX" ]]; then
  run "$TDSX" "$OUT/boost-probe.elf" "$OUT/boost-probe.3dsx"
  echo "    PASS $OUT/boost-probe.3dsx" | tee -a "$LOG"
fi

# ---- 3. what got pulled in --------------------------------------------------
echo "==> Undefined symbols in boost_probe.o that are not libstdc++/libc/libctru:" | tee -a "$LOG"
"$NM" -C -u "$OUT/boost_probe.o" | grep -E 'boost::|__atomic_|__sync_' | sed 's/^/    /' | tee -a "$LOG" || echo "    (none)" | tee -a "$LOG"
echo "==> Archive members linked from outside libstdc++/libsupc++/libc/libm/libgcc/libctru/crt:" | tee -a "$LOG"
grep -E '^/.*\.a\(' "$OUT/boost-probe.map" | sed -E 's/\(.*//' | sort -u \
  | grep -vE '/lib(stdc\+\+|supc\+\+|c|g|m|gcc|ctru|sysbase)\.a$' | sed 's/^/    /' | tee -a "$LOG" || echo "    (none)" | tee -a "$LOG"
echo "==> Entropy-related symbols in the final ELF:" | tee -a "$LOG"
"$NM" "$OUT/boost-probe.elf" | grep -E ' (getentropy|_getentropy_r|arc4random|getrandom|PS_GenerateRandomBytes|_ZNSt13random_device[0-9A-Za-z_]*)$' \
  | sed 's/^/    /' | tee -a "$LOG" || echo "    (none)" | tee -a "$LOG"
echo "==> Done. Log: $LOG"
